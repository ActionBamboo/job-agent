def catalog(source: str, cities: list[str] | None = None) -> dict:
    """返回某个平台的求职意向目录（分类 + 城市 + 常用词）。"""
    conf = PLATFORMS.get(source)
    groups = conf["groups"] if conf else GENERIC_GROUPS
    popular = _POPULAR.get(source) or [g["items"][0] for g in groups[:5] if g["items"]]
    return {
        "source": source,
        "name": conf.get("name", source) if conf else source,
        "note": conf.get("note", "") if conf else "该平台没有内置职位分类，可直接输入关键词抓取。",
        "groups": groups,
        "popular": popular,
        "cities": cities or DEFAULT_CITIES,
        "has_preset": conf is not None,
    }


def is_known(source: str) -> bool:
    return source in PLATFORMS
